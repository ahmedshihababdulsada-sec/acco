import { normalizePhone, tryNormalizePhone } from '../src/customers/phone';

describe('توحيد رقم الموبايل', () => {
  it.each([
    ['07701234567', '+9647701234567'],
    ['0770 123 4567', '+9647701234567'],
    ['0770-123-4567', '+9647701234567'],
    ['+964 770 123 4567', '+9647701234567'],
    ['009647701234567', '+9647701234567'],
    ['9647701234567', '+9647701234567'],
    ['7701234567', '+9647701234567'],
    ['٠٧٧٠١٢٣٤٥٦٧', '+9647701234567'],
    ['(0770) 123.4567', '+9647701234567'],
  ])('%s → %s', (raw, expected) => expect(normalizePhone(raw)).toBe(expected));

  it.each(['', '123', '0770123456', '077012345678', '+9647', '06701234567', 'abc', '+1 415 555 0100', '964 8701234567', '+96477012345678'])('يرفض "%s"', (raw) => {
    expect(() => normalizePhone(raw)).toThrow();
    expect(tryNormalizePhone(raw)).toBeNull();
  });
});
